DROP TABLE IF EXISTS sales_order_item    CASCADE;
DROP TABLE IF EXISTS sales_order         CASCADE;
DROP TABLE IF EXISTS purchase_order_item CASCADE;
DROP TABLE IF EXISTS purchase_order      CASCADE;
DROP TABLE IF EXISTS inventory           CASCADE;
DROP TABLE IF EXISTS customer            CASCADE;
DROP TABLE IF EXISTS employee            CASCADE;
DROP TABLE IF EXISTS warehouse           CASCADE;
DROP TABLE IF EXISTS product             CASCADE;
DROP TABLE IF EXISTS supplier            CASCADE;
DROP TABLE IF EXISTS category            CASCADE;

-- 1) CATEGORY -----------------------------------------------------------
CREATE TABLE category (
    category_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    category_name  VARCHAR(50)  NOT NULL,
    description    VARCHAR(200),
    CONSTRAINT pk_category      PRIMARY KEY (category_id),
    CONSTRAINT uq_category_name UNIQUE (category_name)
);

-- 2) SUPPLIER -----------------------------------------------------------
CREATE TABLE supplier (
    supplier_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    supplier_name  VARCHAR(100) NOT NULL,
    contact_name   VARCHAR(100),
    phone          VARCHAR(20)  NOT NULL,
    email          VARCHAR(100),
    city           VARCHAR(50),
    CONSTRAINT pk_supplier       PRIMARY KEY (supplier_id),
    CONSTRAINT uq_supplier_email UNIQUE (email),
    CONSTRAINT ck_supplier_email CHECK (email LIKE '%_@_%._%')
);

-- 3) PRODUCT ------------------------------------------------------------
CREATE TABLE product (
    product_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    sku            VARCHAR(20)   NOT NULL,
    product_name   VARCHAR(100)  NOT NULL,
    unit           VARCHAR(10)   NOT NULL DEFAULT 'pcs',
    unit_price     NUMERIC(10,2) NOT NULL,
    reorder_level  INTEGER       NOT NULL DEFAULT 10,
    category_id    INTEGER       NOT NULL,
    supplier_id    INTEGER       NOT NULL,
    CONSTRAINT pk_product          PRIMARY KEY (product_id),
    CONSTRAINT uq_product_sku      UNIQUE (sku),
    CONSTRAINT ck_product_price    CHECK (unit_price > 0),
    CONSTRAINT ck_product_reorder  CHECK (reorder_level >= 0),
    CONSTRAINT ck_product_unit     CHECK (unit IN ('pcs','box','kg','lt','m')),
    CONSTRAINT fk_product_category FOREIGN KEY (category_id)
        REFERENCES category (category_id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_supplier FOREIGN KEY (supplier_id)
        REFERENCES supplier (supplier_id) ON DELETE RESTRICT
);

-- 4) WAREHOUSE ----------------------------------------------------------
CREATE TABLE warehouse (
    warehouse_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    warehouse_name VARCHAR(50)  NOT NULL,
    city           VARCHAR(50)  NOT NULL,
    address        VARCHAR(200),
    capacity       INTEGER      NOT NULL,
    CONSTRAINT pk_warehouse          PRIMARY KEY (warehouse_id),
    CONSTRAINT uq_warehouse_name     UNIQUE (warehouse_name),
    CONSTRAINT ck_warehouse_capacity CHECK (capacity > 0)
);

-- 5) EMPLOYEE -----------------------------------------------------------
CREATE TABLE employee (
    employee_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    first_name     VARCHAR(50)  NOT NULL,
    last_name      VARCHAR(50)  NOT NULL,
    job_role       VARCHAR(30)  NOT NULL,
    phone          VARCHAR(20),
    email          VARCHAR(100),
    hire_date      DATE         NOT NULL DEFAULT CURRENT_DATE,
    warehouse_id   INTEGER      NOT NULL,
    CONSTRAINT pk_employee        PRIMARY KEY (employee_id),
    CONSTRAINT uq_employee_email  UNIQUE (email),
    CONSTRAINT ck_employee_role   CHECK (job_role IN
        ('Warehouse Manager','Stock Clerk','Purchasing Officer','Sales Representative')),
    CONSTRAINT fk_employee_wh     FOREIGN KEY (warehouse_id)
        REFERENCES warehouse (warehouse_id) ON DELETE RESTRICT
);

-- 6) CUSTOMER -----------------------------------------------------------
CREATE TABLE customer (
    customer_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    customer_name  VARCHAR(100) NOT NULL,
    phone          VARCHAR(20)  NOT NULL,
    email          VARCHAR(100),
    city           VARCHAR(50),
    CONSTRAINT pk_customer       PRIMARY KEY (customer_id),
    CONSTRAINT uq_customer_email UNIQUE (email)
);

-- 7) INVENTORY  (M:N relationship STORED_IN between PRODUCT and WAREHOUSE)
CREATE TABLE inventory (
    product_id     INTEGER   NOT NULL,
    warehouse_id   INTEGER   NOT NULL,
    quantity       INTEGER   NOT NULL DEFAULT 0,
    shelf_location VARCHAR(10),
    last_updated   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_inventory     PRIMARY KEY (product_id, warehouse_id),
    CONSTRAINT ck_inventory_qty CHECK (quantity >= 0),
    CONSTRAINT fk_inventory_product   FOREIGN KEY (product_id)
        REFERENCES product (product_id) ON DELETE CASCADE,
    CONSTRAINT fk_inventory_warehouse FOREIGN KEY (warehouse_id)
        REFERENCES warehouse (warehouse_id) ON DELETE CASCADE
);

-- 8) PURCHASE_ORDER (stock coming IN from suppliers) --------------------
CREATE TABLE purchase_order (
    po_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    order_date     DATE        NOT NULL DEFAULT CURRENT_DATE,
    status         VARCHAR(15) NOT NULL DEFAULT 'Pending',
    supplier_id    INTEGER     NOT NULL,
    employee_id    INTEGER     NOT NULL,
    warehouse_id   INTEGER     NOT NULL,
    CONSTRAINT pk_purchase_order PRIMARY KEY (po_id),
    CONSTRAINT ck_po_status CHECK (status IN ('Pending','Received','Cancelled')),
    CONSTRAINT fk_po_supplier  FOREIGN KEY (supplier_id)
        REFERENCES supplier (supplier_id) ON DELETE RESTRICT,
    CONSTRAINT fk_po_employee  FOREIGN KEY (employee_id)
        REFERENCES employee (employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_po_warehouse FOREIGN KEY (warehouse_id)
        REFERENCES warehouse (warehouse_id) ON DELETE RESTRICT
);

-- 9) PURCHASE_ORDER_ITEM (M:N relationship between PURCHASE_ORDER and PRODUCT)
CREATE TABLE purchase_order_item (
    po_id          INTEGER       NOT NULL,
    product_id     INTEGER       NOT NULL,
    quantity       INTEGER       NOT NULL,
    unit_cost      NUMERIC(10,2) NOT NULL,
    CONSTRAINT pk_po_item      PRIMARY KEY (po_id, product_id),
    CONSTRAINT ck_po_item_qty  CHECK (quantity > 0),
    CONSTRAINT ck_po_item_cost CHECK (unit_cost > 0),
    CONSTRAINT fk_po_item_po      FOREIGN KEY (po_id)
        REFERENCES purchase_order (po_id) ON DELETE CASCADE,
    CONSTRAINT fk_po_item_product FOREIGN KEY (product_id)
        REFERENCES product (product_id) ON DELETE RESTRICT
);

-- 10) SALES_ORDER (stock going OUT to customers) ------------------------
CREATE TABLE sales_order (
    so_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    order_date     DATE        NOT NULL DEFAULT CURRENT_DATE,
    status         VARCHAR(15) NOT NULL DEFAULT 'Pending',
    customer_id    INTEGER     NOT NULL,
    employee_id    INTEGER     NOT NULL,
    warehouse_id   INTEGER     NOT NULL,
    CONSTRAINT pk_sales_order PRIMARY KEY (so_id),
    CONSTRAINT ck_so_status CHECK (status IN ('Pending','Shipped','Delivered','Cancelled')),
    CONSTRAINT fk_so_customer  FOREIGN KEY (customer_id)
        REFERENCES customer (customer_id) ON DELETE RESTRICT,
    CONSTRAINT fk_so_employee  FOREIGN KEY (employee_id)
        REFERENCES employee (employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_so_warehouse FOREIGN KEY (warehouse_id)
        REFERENCES warehouse (warehouse_id) ON DELETE RESTRICT
);

-- 11) SALES_ORDER_ITEM (M:N relationship between SALES_ORDER and PRODUCT)
CREATE TABLE sales_order_item (
    so_id          INTEGER       NOT NULL,
    product_id     INTEGER       NOT NULL,
    quantity       INTEGER       NOT NULL,
    unit_price     NUMERIC(10,2) NOT NULL,
    CONSTRAINT pk_so_item       PRIMARY KEY (so_id, product_id),
    CONSTRAINT ck_so_item_qty   CHECK (quantity > 0),
    CONSTRAINT ck_so_item_price CHECK (unit_price > 0),
    CONSTRAINT fk_so_item_so      FOREIGN KEY (so_id)
        REFERENCES sales_order (so_id) ON DELETE CASCADE,
    CONSTRAINT fk_so_item_product FOREIGN KEY (product_id)
        REFERENCES product (product_id) ON DELETE RESTRICT
);
