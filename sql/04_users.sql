-- CMPE341 - Stock Management System
-- 04_users.sql : Application users for login (authentication) and
--                roles (authorization). Passwords are stored HASHED
--                (PBKDF2-SHA256 with a random salt, werkzeug.security).
-- =====================================================================

DROP TABLE IF EXISTS app_user CASCADE;

CREATE TABLE app_user (
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    username       VARCHAR(30)  NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    full_name      VARCHAR(100) NOT NULL,
    role           VARCHAR(10)  NOT NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_app_user          PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_username UNIQUE (username),
    CONSTRAINT ck_app_user_role     CHECK (role IN ('admin', 'staff'))
);

