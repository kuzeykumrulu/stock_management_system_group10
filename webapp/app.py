def table_or_404(name):
    if name not in TABLES:
        abort(404)
    return TABLES[name]


def fk_options(cur, fk):
    ref_table, ref_pk, label_sql = fk
    cur.execute(f"SELECT {ref_pk} AS id, {label_sql} AS label FROM {ref_table} ORDER BY {ref_pk}")
    return cur.fetchall()


def form_values(cfg, include_auto_pk):
    """Read submitted form values (empty string -> NULL)."""
    cols, vals = [], []
    for col, _label, _typ, _extra in cfg["fields"]:
        if cfg["auto"] and col in cfg["pk"] and not include_auto_pk:
            continue
        v = request.form.get(col, "").strip()
        cols.append(col)
        vals.append(v if v != "" else None)
    return cols, vals


def pk_from_args(cfg):
    return [request.args.get(c) for c in cfg["pk"]]


# ---------------------------------------------------------------------------
# AUTHORIZATION - permissions of each role
#   admin : full access (view / insert / update / delete) to every table,
#           and can manage application users.
#   staff : can view every table; can insert and update only the daily
#           operational tables (stock, orders, customers); cannot delete and
#           cannot change master data (categories, suppliers, products,
#           warehouses, employees).
# ---------------------------------------------------------------------------
STAFF_EDITABLE = {"inventory", "customer", "purchase_order", "purchase_order_item",
                  "sales_order", "sales_order_item"}


def can(action, table=None):
    role = session.get("role")
    if role == "admin":
        return True
    if role == "staff":
        if action == "view":
            return True
        if action in ("insert", "update"):
            return table in STAFF_EDITABLE
    return False


def login_required(view):
    @wraps(view)
    def wrapper(*args, **kwargs):
        if "user_id" not in session:
            return redirect(url_for("login", next=request.path))
        return view(*args, **kwargs)
    return wrapper


def require(action):
    """Decorator: the logged-in user's role must allow <action> on <name>."""
    def deco(view):
        @wraps(view)
        def wrapper(*args, **kwargs):
            if not can(action, kwargs.get("name")):
                flash(f"Access denied: the '{session.get('role')}' role is not allowed "
                      f"to {action} records in this table.", "err")
                return redirect(url_for("list_rows", name=kwargs["name"])
                                if kwargs.get("name") in TABLES and can("view") else url_for("index"))
            return view(*args, **kwargs)
        return wrapper
    return deco


@app.context_processor
def inject_auth():
    return dict(can=can, current_user=session.get("username"),
                current_role=session.get("role"), current_name=session.get("full_name"))


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")
        with get_conn() as conn, conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
            cur.execute("SELECT user_id, username, password_hash, full_name, role "
                        "FROM app_user WHERE username = %s", (username,))
            user = cur.fetchone()
        # The password is never compared in plain text: the entered password is
        # hashed with the stored salt and compared with the stored hash.
        if user and check_password_hash(user["password_hash"], password):
            session.clear()
            session.update(user_id=user["user_id"], username=user["username"],
                           full_name=user["full_name"], role=user["role"])
            flash(f"Welcome, {user['full_name']} ({user['role']}).", "ok")
            nxt = request.args.get("next", "")
            return redirect(nxt if nxt.startswith("/") and not nxt.startswith("//") else url_for("index"))
        flash("Invalid username or password.", "err")
    return render_template("login.html")


@app.route("/logout")
def logout():
    session.clear()
    flash("You have been logged out.", "ok")
    return redirect(url_for("login"))


@app.route("/users", methods=["GET", "POST"])
@login_required
def users():
    if session.get("role") != "admin":
        flash("Access denied: only the admin role can manage users.", "err")
        return redirect(url_for("index"))
    if request.method == "POST":
        username = request.form.get("username", "").strip()
        full_name = request.form.get("full_name", "").strip()
        password = request.form.get("password", "")
        role = request.form.get("role", "staff")
        if len(password) < 8:
            flash("Password must be at least 8 characters.", "err")
        else:
            try:
                with get_conn() as conn, conn.cursor() as cur:
                    cur.execute("INSERT INTO app_user (username, password_hash, full_name, role) "
                                "VALUES (%s, %s, %s, %s)",
                                (username, generate_password_hash(password, method="pbkdf2:sha256"),
                                 full_name, role))
                flash(f"User '{username}' created.", "ok")
                return redirect(url_for("users"))
            except psycopg2.Error as e:
                flash(f"Insert failed: {e.pgerror or e}", "err")
    with get_conn() as conn, conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        cur.execute("SELECT user_id, username, full_name, role, password_hash, created_at "
                    "FROM app_user ORDER BY user_id")
        rows = cur.fetchall()
    return render_template("users.html", rows=rows, tables=TABLES)


@app.route("/users/<int:user_id>/delete", methods=["POST"])
@login_required
def delete_user(user_id):
    if session.get("role") != "admin":
        abort(403)
    if user_id == session.get("user_id"):
        flash("You cannot delete your own account.", "err")
    else:
        with get_conn() as conn, conn.cursor() as cur:
            cur.execute("DELETE FROM app_user WHERE user_id = %s", (user_id,))
        flash("User deleted.", "ok")
    return redirect(url_for("users"))


@app.route("/")
@login_required
def index():
    with get_conn() as conn, conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        counts = {}
        for t in TABLES:
            cur.execute(f"SELECT COUNT(*) AS n FROM {t}")
            counts[t] = cur.fetchone()["n"]
        # Low-stock report (same logic as query Q3 in the report)
        cur.execute("""
            SELECT p.sku, p.product_name, p.reorder_level,
                   (SELECT COALESCE(SUM(i.quantity),0) FROM inventory i
                     WHERE i.product_id = p.product_id) AS total_stock
            FROM product p
            WHERE p.reorder_level > (SELECT COALESCE(SUM(i.quantity),0) FROM inventory i
                                      WHERE i.product_id = p.product_id)
            ORDER BY p.sku""")
        low = cur.fetchall()
    return render_template("index.html", tables=TABLES, counts=counts, low=low)


@app.route("/t/<name>")
@login_required
def list_rows(name):
    cfg = table_or_404(name)
    with get_conn() as conn, conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        cur.execute(f"SELECT * FROM {name} ORDER BY {', '.join(cfg['pk'])}")
        rows = cur.fetchall()
        labels = {}
        for col, _l, typ, extra in cfg["fields"]:
            if typ == "fk":
                labels[col] = {r["id"]: r["label"] for r in fk_options(cur, extra)}
    return render_template("list.html", name=name, cfg=cfg, rows=rows, labels=labels, tables=TABLES)


@app.route("/t/<name>/new", methods=["GET", "POST"])
@login_required
@require("insert")
def insert_row(name):
    cfg = table_or_404(name)
    if request.method == "POST":
        cols, vals = form_values(cfg, include_auto_pk=False)
        sql = f"INSERT INTO {name} ({', '.join(cols)}) VALUES ({', '.join(['%s'] * len(vals))})"
        try:
            with get_conn() as conn, conn.cursor() as cur:
                cur.execute(sql, vals)
            flash("Record inserted successfully.", "ok")
            return redirect(url_for("list_rows", name=name))
        except psycopg2.Error as e:
            flash(f"Insert failed: {e.pgerror or e}", "err")
    return render_form(name, cfg, row=request.form or {}, mode="insert")


@app.route("/t/<name>/edit", methods=["GET", "POST"])
@login_required
@require("update")
def update_row(name):
    cfg = table_or_404(name)
    keys = pk_from_args(cfg)
    where = " AND ".join(f"{c} = %s" for c in cfg["pk"])
    if request.method == "POST":
        cols, vals = form_values(cfg, include_auto_pk=False)
        cols_vals = [(c, v) for c, v in zip(cols, vals) if c not in cfg["pk"]]
        sets = ", ".join(f"{c} = %s" for c, _ in cols_vals)
        if name == "inventory":
            sets += ", last_updated = CURRENT_TIMESTAMP"
        sql = f"UPDATE {name} SET {sets} WHERE {where}"
        try:
            with get_conn() as conn, conn.cursor() as cur:
                cur.execute(sql, [v for _, v in cols_vals] + keys)
            flash("Record updated successfully.", "ok")
            return redirect(url_for("list_rows", name=name))
        except psycopg2.Error as e:
            flash(f"Update failed: {e.pgerror or e}", "err")
            return render_form(name, cfg, row=request.form, mode="update", keys=keys)
    with get_conn() as conn, conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        cur.execute(f"SELECT * FROM {name} WHERE {where}", keys)
        row = cur.fetchone()
    if not row:
        abort(404)
    return render_form(name, cfg, row=row, mode="update", keys=keys)


@app.route("/t/<name>/delete", methods=["POST"])
@login_required
@require("delete")
def delete_row(name):
    cfg = table_or_404(name)
    keys = [request.form.get(c) for c in cfg["pk"]]
    where = " AND ".join(f"{c} = %s" for c in cfg["pk"])
    try:
        with get_conn() as conn, conn.cursor() as cur:
            cur.execute(f"DELETE FROM {name} WHERE {where}", keys)
        flash("Record deleted successfully.", "ok")
    except psycopg2.Error as e:
        flash(f"Delete failed: {e.pgerror or e}", "err")
    return redirect(url_for("list_rows", name=name))


def render_form(name, cfg, row, mode, keys=None):
    with get_conn() as conn, conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        options = {col: fk_options(cur, extra) for col, _l, typ, extra in cfg["fields"] if typ == "fk"}
    return render_template("form.html", name=name, cfg=cfg, row=row, mode=mode,
                           options=options, keys=keys, tables=TABLES)


@app.template_filter("fmt")
def fmt(v):
    if v is None:
        return ""
    if isinstance(v, Decimal):
        return f"{v:,.2f}"
    if hasattr(v, "strftime"):
        return v.strftime("%Y-%m-%d %H:%M") if hasattr(v, "hour") else v.strftime("%Y-%m-%d")
    return v


